#!/usr/bin/env node
/**
 * Pure Node.js XLSX generator — no AI, no API key required.
 * Claude Code calls this after generating JSON outputs.
 *
 * Usage:
 *   node scripts/generate_xlsx.js brd     [outputDir] [clientSlug]
 *   node scripts/generate_xlsx.js sprint  [outputDir] [clientSlug]
 *   node scripts/generate_xlsx.js all     [outputDir] [clientSlug]
 *
 * Examples:
 *   node scripts/generate_xlsx.js brd "opportunities/Northwind Utilities" northwind
 *   node scripts/generate_xlsx.js all "opportunities/ACME Electronics"  acme
 *
 * The BRD is produced by populating templates/brd_template.xlsx — the template
 * is the single source of truth for BRD sheets, columns, and styling.
 */

const ExcelJS = require('exceljs');
const fs = require('fs');
const path = require('path');

// argv[2] = command, argv[3] = outputDir, argv[4] = clientSlug
const RAW_OUTPUT_DIR = process.argv[3] || 'outputs';
const CLIENT_SLUG    = process.argv[4] || '';

// Resolve relative to the caller's current working directory (this script
// lives in the user-level presales-agent skill, not inside the client project)
const OUTPUTS = path.resolve(process.cwd(), RAW_OUTPUT_DIR);

// Build a prefixed filename: "northwind_brd.json" or "brd.json" if no slug
function fileName(base) {
  return CLIENT_SLUG ? `${CLIENT_SLUG}_${base}` : base;
}

function fail(msg) {
  console.error(`❌ ${msg}`);
  process.exit(1);
}

function readJson(base) {
  const p = path.join(OUTPUTS, fileName(base));
  if (!fs.existsSync(p)) fail(`${p} not found. Claude must generate it first.`);
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

// ─── BRD ──────────────────────────────────────────────────────────────────────
// The BRD is generated by POPULATING templates/brd_template.xlsx, never by
// rebuilding sheets from scratch. Sheet names, headers, widths, and cell styles
// come from the template; row 2 of each table sheet is a styled blank row that
// every data row copies.

const TEMPLATE_PATH = path.join(__dirname, '..', 'templates', 'brd_template.xlsx');

const SHEETS = {
  scope: {
    name: 'Scope of Work',
    headers: ['Requirement ID', 'Business Area', 'Sub Business Module', 'Requirement',
      'Requirement Description', 'Information Required from {Client}',
      'Solution Approach', 'Effort (Hours)'],
  },
  oos: {
    name: 'Out of Scope',
    headers: ['Requirement ID', 'Business Area', 'Requirement', 'Not Included in This Scope'],
  },
  guide: { name: 'Business Process Guide' },
  summary: {
    name: 'Effort Summary',
    headers: ['Business Area', 'Requirements', 'Effort (Hours)'],
  },
};
const GUIDE_STEP_HEADER_ROW = 5;

// Bullet lists render the way the client reads them: "• point", blank line between.
function bullets(value) {
  const items = (Array.isArray(value) ? value : [value]).map((s) => String(s || '').trim()).filter(Boolean);
  return items.map((s) => `• ${s}`).join('\n\n');
}

// Requirement IDs sort numerically ("5.10" after "5.9"), not as strings.
function compareIds(a, b) {
  const pa = String(a).split('.').map(Number);
  const pb = String(b).split('.').map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
}

function checkHeaders(ws, expected, client) {
  expected.forEach((h, i) => {
    const actual = String(ws.getCell(1, i + 1).value || '').trim();
    if (actual !== h) {
      fail(`Template mismatch on "${ws.name}" column ${i + 1}: expected "${h}", found "${actual}".\n` +
        '   templates/brd_template.xlsx has changed shape. Update SHEETS in this script to match.');
    }
    ws.getCell(1, i + 1).value = h.replace('{Client}', client);
  });
}

// Copy the template's style row onto rowNumber and write values into it.
function writeRow(ws, rowNumber, values, styleRow = 2) {
  values.forEach((v, i) => {
    const cell = ws.getCell(rowNumber, i + 1);
    cell.style = JSON.parse(JSON.stringify(ws.getCell(styleRow, i + 1).style || {}));
    cell.value = v;
  });
}

function validateBrd(doc) {
  if (Array.isArray(doc)) {
    fail('BRD JSON is a bare array — that is the retired assumption-based format.\n' +
      '   The BRD is now an object: { clientName, rows, processSteps, glossary }. See schemas/brd_row.ts.');
  }
  if (!doc.clientName) fail('BRD JSON is missing clientName.');
  if (!Array.isArray(doc.rows) || doc.rows.length === 0) fail('BRD JSON has no rows.');
  const seen = new Set();
  for (const r of doc.rows) {
    const id = r.requirementId || '(no id)';
    for (const key of ['requirementId', 'businessArea', 'subBusinessModule', 'requirement', 'solutionApproach']) {
      if (!r[key]) fail(`Row ${id} is missing ${key}.`);
    }
    if (!Array.isArray(r.description) || r.description.length === 0) fail(`Row ${id} has no description points.`);
    if (typeof r.effortHours !== 'number') fail(`Row ${id} has no numeric effortHours.`);
    if (seen.has(id)) fail(`Requirement ID ${id} is used twice.`);
    seen.add(id);
  }
}

async function generateBrdXlsx() {
  const doc = readJson('brd.json');
  validateBrd(doc);
  if (!fs.existsSync(TEMPLATE_PATH)) fail(`BRD template missing at ${TEMPLATE_PATH}. The skill install is incomplete.`);

  const client = doc.clientName;
  const rows = [...doc.rows].sort((a, b) => compareIds(a.requirementId, b.requirementId));

  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(TEMPLATE_PATH);
  for (const s of Object.values(SHEETS)) {
    if (!wb.getWorksheet(s.name)) fail(`Template is missing the "${s.name}" sheet.`);
  }

  // ── Scope of Work ──
  const sow = wb.getWorksheet(SHEETS.scope.name);
  checkHeaders(sow, SHEETS.scope.headers, client);
  rows.forEach((r, i) => writeRow(sow, 2 + i, [
    String(r.requirementId),
    r.businessArea,
    r.subBusinessModule,
    r.requirement,
    bullets(r.description),
    r.informationRequired && r.informationRequired.length ? bullets(r.informationRequired) : 'None',
    r.solutionApproach,
    r.effortHours,
  ]));
  sow.autoFilter = { from: 'A1', to: { row: 1 + rows.length, column: SHEETS.scope.headers.length } };

  // ── Out of Scope — only requirements that carry an exclusion ──
  const oos = wb.getWorksheet(SHEETS.oos.name);
  checkHeaders(oos, SHEETS.oos.headers, client);
  const oosRows = rows.filter((r) => r.notIncluded && r.notIncluded.length);
  oosRows.forEach((r, i) => writeRow(oos, 2 + i, [
    String(r.requirementId), r.businessArea, r.requirement, bullets(r.notIncluded),
  ]));
  if (!oosRows.length) writeRow(oos, 2, ['', '', '', 'No exclusions recorded.']);

  // ── Business Process Guide ──
  const guide = wb.getWorksheet(SHEETS.guide.name);
  guide.getCell('A1').value = String(guide.getCell('A1').value || '').replace('{Client}', client);
  guide.getCell('A3').value = doc.processSummary || '';
  const steps = doc.processSteps || [];
  const stepStyleRow = GUIDE_STEP_HEADER_ROW + 1;
  steps.forEach((s, i) => writeRow(guide, stepStyleRow + i,
    [`${i + 1}. ${s.step}`, s.whatHappens, s.where], stepStyleRow));
  if (!steps.length) writeRow(guide, stepStyleRow, ['', 'Process steps to be confirmed in Discovery.', ''], stepStyleRow);

  // Glossary sits below the steps, reusing the step table's header and body styles.
  const glossary = doc.glossary || [];
  if (glossary.length) {
    let r = stepStyleRow + Math.max(steps.length, 1) + 2;
    guide.getCell(r, 1).value = 'Common Business Terms';
    guide.getCell(r, 1).style = { font: { name: 'Aptos', size: 12, bold: true } };
    r += 1;
    writeRow(guide, r, ['Term', 'Plain Meaning', 'Used For'], GUIDE_STEP_HEADER_ROW);
    glossary.forEach((t, i) => writeRow(guide, r + 1 + i, [t.term, t.meaning, t.usedFor || ''], stepStyleRow));
  }

  // ── Effort Summary ──
  const sum = wb.getWorksheet(SHEETS.summary.name);
  checkHeaders(sum, SHEETS.summary.headers, client);
  const areas = new Map();
  for (const r of rows) {
    const a = areas.get(r.businessArea) || { count: 0, effort: 0 };
    a.count += 1; a.effort += r.effortHours;
    areas.set(r.businessArea, a);
  }
  let line = 2;
  for (const [area, a] of areas) writeRow(sum, line++, [area, a.count, Math.round(a.effort * 10) / 10]);
  const grand = rows.reduce((s, r) => s + r.effortHours, 0);
  writeRow(sum, line, ['TOTAL', rows.length, Math.round(grand * 10) / 10]);
  sum.getRow(line).eachCell((c) => { c.font = { ...c.font, bold: true }; });

  const outPath = path.join(OUTPUTS, fileName('brd.xlsx'));
  await wb.xlsx.writeFile(outPath);
  console.log(`✅ ${fileName('brd.xlsx')} — ${rows.length} requirements, ${oosRows.length} with exclusions, ${Math.round(grand)}h total (from template)`);
}

// ─── Sprint Plan ──────────────────────────────────────────────────────────────
// Sprint plan and timeline have no template; they are plain tables with a bold header.

function addTable(wb, name, aoa) {
  const ws = wb.addWorksheet(name);
  aoa.forEach((row) => ws.addRow(row));
  ws.getRow(1).font = { bold: true };
  ws.columns.forEach((col) => {
    let max = 8;
    col.eachCell({ includeEmpty: false }, (c) => { max = Math.max(max, String(c.value).length + 2); });
    col.width = Math.min(max, 50);
  });
  return ws;
}

async function generateSprintXlsx() {
  const plan = readJson('sprint_plan.json');
  const { parameters: p, moduleEfforts, weeklyGrid, roleHourSummary } = plan;

  const wb = new ExcelJS.Workbook();

  // Sheet 1: Module Summary
  const modData = [['Business Area', 'Phase', 'Total Effort (h)', 'Data Load (h)', 'Dev Effort (h)']];
  for (const m of (moduleEfforts || [])) {
    modData.push([m.module, m.phase, m.totalEffort, m.dataLoadEffort, m.devEffort]);
  }
  if (p) modData.push(['GRAND TOTAL', '', p.totalGrandEffort, p.totalDataLoadEffort, p.totalDevEffort]);
  addTable(wb, 'Module Summary', modData);

  // Sheet 2: Sprint Parameters
  if (p) {
    addTable(wb, 'Sprint Parameters', [
      ['Parameter', 'Value'],
      ['Number of Developers', p.numberOfDevelopers],
      ['Dev Capacity per Sprint (h)', p.devCapacityPerSprint],
      ['Grand Total Effort (h)', p.totalGrandEffort],
      ['Data Load Effort (h)', p.totalDataLoadEffort],
      ['Dev Effort (excl. data load) (h)', p.totalDevEffort],
      ['Number of Sprints', p.numberOfSprints],
      ['Balance Effort (h)', p.balanceEffort],
      ['Pre-Sprint Weeks', p.preSprintWeeks],
      ['Post-Sprint Weeks', p.postSprintWeeks],
      ['Total Project Weeks', p.totalProjectWeeks],
      ['Total Project Duration (months)', +(p.totalProjectWeeks / 4.33).toFixed(1)],
    ]);
  }

  // Sheet 3: Sprint Grid
  if (weeklyGrid && weeklyGrid.length > 0) {
    const devCount = weeklyGrid[0]?.allocation?.developers?.length || 1;
    const gridData = [[
      'Week', 'Sprint', 'Phase', 'BA (h)', 'SA (h)',
      ...Array.from({ length: devCount }, (_, i) => `TS-${i + 1} (h)`),
      'DS (h)', 'QA (h)', 'Total (h)',
    ]];
    for (const w of weeklyGrid) {
      gridData.push([
        w.weekNumber, w.sprintNumber || '', w.phase,
        w.allocation.ba, w.allocation.sa,
        ...(w.allocation.developers || []),
        w.allocation.ds, w.allocation.qa,
        w.totalHours,
      ]);
    }
    addTable(wb, 'Sprint Grid', gridData);
  }

  // Sheet 4: Role Hours
  if (roleHourSummary) {
    const rh = roleHourSummary;
    addTable(wb, 'Role Hours', [
      ['Role', 'Total Hours'],
      ['Business Analyst (BA)', rh.ba],
      ['Solution Architect (SA)', rh.sa],
      ...(rh.developers || []).map((d) => [d.name, d.hours]),
      ['Delivery Scrum (DS)', rh.ds],
      ['Quality Assurance (QA)', rh.qa],
      ['GRAND TOTAL', rh.grandTotal],
    ]);
  }

  await wb.xlsx.writeFile(path.join(OUTPUTS, fileName('sprint_plan.xlsx')));
  console.log(`✅ ${fileName('sprint_plan.xlsx')} — ${p?.numberOfSprints || '?'} sprints`);

  // Timeline workbook
  const timelinePath = path.join(OUTPUTS, fileName('timeline.json'));
  const wb2 = new ExcelJS.Workbook();
  let timelineData;
  if (fs.existsSync(timelinePath)) {
    const tl = JSON.parse(fs.readFileSync(timelinePath, 'utf8'));
    timelineData = [
      ['#', 'Task Title', 'Owner', 'Start Week', 'End Week', 'Duration (wks)', 'Effort (h)', 'Phase'],
      ...(tl.phases || []).map((ph) => [
        ph.serial, ph.taskTitle, ph.taskOwner,
        ph.startWeek, ph.endWeek, ph.endWeek - ph.startWeek + 1,
        ph.effortHours || '', ph.phase,
      ]),
      ['', 'TOTAL PROJECT', '', 1, tl.totalWeeks, tl.totalWeeks, p?.totalGrandEffort || '', ''],
    ];
  } else {
    timelineData = [['Note'], ['Run Claude to generate timeline.json for detailed view']];
  }
  addTable(wb2, 'Timeline', timelineData);
  await wb2.xlsx.writeFile(path.join(OUTPUTS, fileName('timeline.xlsx')));
  console.log(`✅ ${fileName('timeline.xlsx')}`);
}

// ─── Entry point ─────────────────────────────────────────────────────────────
async function main() {
  const cmd = process.argv[2] || 'all';
  if (!fs.existsSync(OUTPUTS)) fs.mkdirSync(OUTPUTS, { recursive: true });

  switch (cmd) {
    case 'brd':
    case 'scope': // legacy alias — the scope matrix is now the BRD
      await generateBrdXlsx();
      break;
    case 'sprint':
      await generateSprintXlsx();
      break;
    case 'all':
      if (fs.existsSync(path.join(OUTPUTS, fileName('brd.json'))))         await generateBrdXlsx();
      if (fs.existsSync(path.join(OUTPUTS, fileName('sprint_plan.json')))) await generateSprintXlsx();
      break;
    default:
      fail(`Unknown command: ${cmd}. Use: brd | sprint | all`);
  }
}

main().catch((err) => fail(err.stack || String(err)));
